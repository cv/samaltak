#!/usr/bin/env python3
"""Turn a PEM CA bundle into src/System-TLS/TrustStoreRoots.st: the trust anchors of TrustStore default.

usage: tools/ca-bundle-to-smalltalk.py [BUNDLE] [OUTPUT]
  BUNDLE  PEM certificates (default /etc/ssl/certs/ca-certificates.crt: Mozilla's roots on Debian and Ubuntu)
  OUTPUT  default src/System-TLS/TrustStoreRoots.st

Each certificate becomes its common name (or subject) and its DER in Base64, sorted by name then DER so that a
regenerated file differs only where the bundle did; TrustStore parses them on first use. Uses only the standard
library; the names come from openssl x509 if it is there, else they are left out.
"""
import base64, hashlib, re, subprocess, sys

bundle = sys.argv[1] if len(sys.argv) > 1 else '/etc/ssl/certs/ca-certificates.crt'
output = sys.argv[2] if len(sys.argv) > 2 else 'src/System-TLS/TrustStoreRoots.st'
REQUIRED = ['Amazon Root CA 1', 'Starfield Services Root Certificate Authority - G2']

def subject_of(pem):
    try:
        out = subprocess.run(['openssl', 'x509', '-noout', '-subject', '-nameopt', 'RFC2253,-esc_msb'],
                             input=pem.encode(), capture_output=True, check=True).stdout.decode('utf-8', 'replace')
    except (OSError, subprocess.CalledProcessError):
        return ''
    out = out.strip()
    return out[len('subject='):] if out.startswith('subject=') else out

def common_name(subject):
    m = re.search(r'(?:^|,)CN=((?:[^,\\]|\\.)*)', subject)
    return m.group(1) if m else subject

text = open(bundle, encoding='ascii', errors='replace').read()
pems = re.findall(r'-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----', text, re.S)
roots = {}
for pem in pems:
    body = ''.join(pem.splitlines()[1:-1])
    der = base64.b64decode(body)
    roots[der] = common_name(subject_of(pem))
if not roots:
    sys.exit('%s: no certificates' % bundle)
entries = sorted(roots.items(), key=lambda kv: (kv[1], kv[0]))
names = [name for _, name in entries]
missing = [r for r in REQUIRED if r not in names] if any(names) else []
if missing:
    sys.exit('%s lacks %s' % (bundle, ', '.join(missing)))

def st_string(s):
    return "'" + s.replace("'", "''") + "'"

digest = hashlib.sha256(b''.join(der for der, _ in entries)).hexdigest()
lines = []
lines.append("Object subclass: #TrustStoreRoots")
lines.append("\tinstanceVariableNames: ''")
lines.append("\tclassVariableNames: ''")
lines.append("\tpackage: 'System-TLS'!")
lines.append("")
lines.append("TrustStoreRoots comment: " + st_string(
    'I am generated by tools/ca-bundle-to-smalltalk.py from a PEM CA bundle (%s here: %d certificates, '
    'SHA-256 of their DERs %s); do not edit me, regenerate me. My class side holds the trust anchors of TrustStore default, '
    'each its name and its DER in Base64, parsed by TrustStore on first use.' % (bundle, len(entries), digest)) + "!")
lines.append("")
lines.append("!TrustStoreRoots class methodsFor: 'roots'!")
lines.append("namesAndCertificates")
lines.append('\t"Pairs: a root\'s name (its common name), its DER in Base64."')
lines.append("\t^#(")
for der, name in entries:
    b64 = base64.b64encode(der).decode()
    lines.append("\t\t" + st_string(name))
    lines.append("\t\t" + st_string(b64))
lines.append("\t)")
lines.append("! !")
open(output, 'w', newline='\n').write('\n'.join(lines) + '\n')
print('%s: %d roots from %s' % (output, len(entries), bundle))
