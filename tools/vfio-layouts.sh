#!/bin/sh
# Generates src/Tests-Devices/VfioLayouts.st: the layouts (sizeof, and every field's offset and size) of the VFIO
# structures VfioPciDevice passes to the kernel and the constants (ioctl requests, flags, region indexes) it uses, as
# the C compiler sees them in Linux's UAPI header linux/vfio.h. VfioLayoutTest compares VfioPciDevice's own tables
# with them, byte for byte. The UAPI is stable: regenerate only to check a new header.
#   tools/vfio-layouts.sh [include directory holding linux/vfio.h] (default: the system's, /usr/include)
set -eu
INC=${1:-/usr/include}
OUT=$(cd "$(dirname "$0")/.." && pwd)/src/Tests-Devices/VfioLayouts.st
[ -f "$INC/linux/vfio.h" ] || { echo "vfio-layouts: no $INC/linux/vfio.h" >&2; exit 1; }
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
cat > "$T/layouts.c" <<'EOF'
#include <stdio.h>
#include <stddef.h>
#include <linux/vfio.h>

#define S(t) printf("\t\t#('%s' %zu #(\n", #t, sizeof(struct t));
#define F(t, f) printf("\t\t\t#('%s' %zu %zu)\n", #f, offsetof(struct t, f), sizeof(((struct t *)0)->f));
#define E printf("\t\t))\n");
#define C(n) printf("\t\t#('%s' %llu)\n", #n, (unsigned long long)(n));

int main(void)
{
    printf("!VfioLayouts class methodsFor: 'layouts'!\nlayouts\n\t\"{name. sizeof. {{field. offset. size}...}}\"\n\t^#(\n");
    S(vfio_group_status) F(vfio_group_status, argsz) F(vfio_group_status, flags) E
    S(vfio_device_info) F(vfio_device_info, argsz) F(vfio_device_info, flags) F(vfio_device_info, num_regions)
        F(vfio_device_info, num_irqs) F(vfio_device_info, cap_offset) F(vfio_device_info, pad) E
    S(vfio_region_info) F(vfio_region_info, argsz) F(vfio_region_info, flags) F(vfio_region_info, index)
        F(vfio_region_info, cap_offset) F(vfio_region_info, size) F(vfio_region_info, offset) E
    S(vfio_iommu_type1_info) F(vfio_iommu_type1_info, argsz) F(vfio_iommu_type1_info, flags)
        F(vfio_iommu_type1_info, iova_pgsizes) F(vfio_iommu_type1_info, cap_offset) F(vfio_iommu_type1_info, pad) E
    S(vfio_iommu_type1_dma_map) F(vfio_iommu_type1_dma_map, argsz) F(vfio_iommu_type1_dma_map, flags)
        F(vfio_iommu_type1_dma_map, vaddr) F(vfio_iommu_type1_dma_map, iova) F(vfio_iommu_type1_dma_map, size) E
    S(vfio_iommu_type1_dma_unmap) F(vfio_iommu_type1_dma_unmap, argsz) F(vfio_iommu_type1_dma_unmap, flags)
        F(vfio_iommu_type1_dma_unmap, iova) F(vfio_iommu_type1_dma_unmap, size) E
    printf("\t)\n!\nconstants\n\t\"{name. value}: the constants VfioPciDevice uses, from the same header.\"\n\t^#(\n");
    C(VFIO_API_VERSION) C(VFIO_TYPE1_IOMMU) C(VFIO_TYPE1v2_IOMMU) C(VFIO_NOIOMMU_IOMMU)
    C(VFIO_GET_API_VERSION) C(VFIO_CHECK_EXTENSION) C(VFIO_SET_IOMMU)
    C(VFIO_GROUP_GET_STATUS) C(VFIO_GROUP_SET_CONTAINER) C(VFIO_GROUP_UNSET_CONTAINER) C(VFIO_GROUP_GET_DEVICE_FD)
    C(VFIO_DEVICE_GET_INFO) C(VFIO_DEVICE_GET_REGION_INFO) C(VFIO_DEVICE_RESET)
    C(VFIO_IOMMU_GET_INFO) C(VFIO_IOMMU_MAP_DMA) C(VFIO_IOMMU_UNMAP_DMA)
    C(VFIO_GROUP_FLAGS_VIABLE) C(VFIO_GROUP_FLAGS_CONTAINER_SET)
    C(VFIO_DEVICE_FLAGS_RESET) C(VFIO_DEVICE_FLAGS_PCI)
    C(VFIO_REGION_INFO_FLAG_READ) C(VFIO_REGION_INFO_FLAG_WRITE) C(VFIO_REGION_INFO_FLAG_MMAP) C(VFIO_REGION_INFO_FLAG_CAPS)
    C(VFIO_DMA_MAP_FLAG_READ) C(VFIO_DMA_MAP_FLAG_WRITE)
    C(VFIO_PCI_BAR0_REGION_INDEX) C(VFIO_PCI_ROM_REGION_INDEX) C(VFIO_PCI_CONFIG_REGION_INDEX) C(VFIO_PCI_NUM_REGIONS)
    printf("\t)\n! !\n");
    return 0;
}
EOF
cc -std=gnu11 -I"$INC" "$T/layouts.c" -o "$T/layouts"
{
    cat <<EOF
Object subclass: #VfioLayouts
	instanceVariableNames: ''
	classVariableNames: ''
	package: 'Tests-Devices'!

VfioLayouts comment: 'I am generated by tools/vfio-layouts.sh from Linux''s linux/vfio.h (the C compiler''s sizeof and offsetof of the VFIO structures VfioPciDevice passes to the kernel, and the constants it uses); do not edit me, regenerate me. VfioLayoutTest compares VfioPciDevice''s tables with mine.'!

EOF
    "$T/layouts"
} > "$OUT"
echo "vfio-layouts: wrote $OUT"
