ALL_HANDLES, NULLABLE = [], set()

def lowtalk_name(fn):
    return "nativeCuda" + fn.name[:1].upper() + fn.name[1:]

def slots(fn):
    """(Lowtalk argument name, C type, tag number) per C slot of the export."""
    out = []
    for tag, p in fn.ffi_args():
        n = p if isinstance(p, str) else camel(p.c)
        if tag in ("bytes", "wbytes"):
            out.append((n, "const uint8_t *" if tag == "bytes" else "uint8_t *", TAG_NUM[tag]))
            out.append((n + "Length", "uint64_t", None))
        else:
            out.append((n, TAG_C[tag], TAG_NUM[tag]))
    return out

def keywords(first, names):
    if not names: return first
    return " ".join(["%s: %s" % (first, names[0])] + ["%s: %s" % (n, n) for n in names[1:]])

def st_string(s):
    return "'" + s.replace("'", "''") + "'"

def gen_lowtalk(libs, fns):
    ext, back = [], []
    ext.append("!FFIPrimitives methodsFor: 'cuda exports (generated by tools/cuda/bindgen.py)'!")
    back.append("CLibrary subclass: #CudaBackend\n\tinstanceVariableNames: ''\n\tclassVariableNames: ''\n\tpackage: 'VM-Jit'!\n")
    back.append("CudaBackend comment: 'NVIDIA''s CUDA libraries (the runtime, the driver API, cuBLAS, cuRAND, cuOpt) behind dlopen, one checked C wrapper a function (vm/native/cudalib_gen.c, cudalib.c: loaded on first use where they are installed; stubs on UEFI). FFIPrimitives exports them to the image as cuda_* (FFIPrimitives-cuda); System-CUDA''s Cuda*API classes use them. %s docs/cuda.md. Not simulated.'!\n" % GENERATED.replace("'", "''"))
    back.append("!CudaBackend class methodsFor: 'declaring'!\nheaders\n\t^#('\"cudalib_gen.h\"')\n! !\n")
    back.append("!CudaBackend methodsFor: 'calls'!")
    for key, export, args, sl in fns:
        names = [s[0] for s in sl]
        tags = [s[2] for s in sl if s[2] is not None]
        lsel = keywords(lowtalk_name_from(export), names)
        lines = [lsel, "\t<function>", "\t<approvedFFI: %d symbol: '%s' arguments: #(%s) result: 3>" % (key, export, " ".join(map(str, tags)))]
        lines += ["\t<var: #%s type: '%s'>" % (n, t) for n, t, _ in sl]
        lines += ["\t<returns: 'int64_t'>", "\t^cudaBackend " + keywords(backend_name(export), names), "!"]
        ext.append("\n".join(lines))
        proto = "int64_t samaltak_%s(%s)" % (export, ", ".join("%s%s%s" % (t, "" if t.endswith("*") else " ", n) for n, t, _ in sl) or "void")
        back.append("%s\n\t<c: '%s'>\n\t^-1\n!" % (keywords(backend_name(export), names), proto))
    ext[-1] += " !"
    back[-1] += " !"
    return "\n".join(ext) + "\n", "\n".join(back) + "\n"

def lowtalk_name_from(export):
    s = export[len("cuda_"):]
    parts = s.split("_")
    s = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return "nativeCuda" + s[:1].upper() + s[1:]

def backend_name(export):
    s = export[len("cuda_"):]
    parts = s.split("_")
    s = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return "call" + s[:1].upper() + s[1:]

def c_proto_of(export, sl):
    return "int64_t samaltak_%s(%s)" % (export, ", ".join("%s%s%s" % (t, "" if t.endswith("*") else " ", c_slot_name(n)) for n, t, _ in sl) or "void")

def c_slot_name(n):
    return n

def st_method(fn):
    args = fn.ffi_args()
    st_params = [camel(p.c) for tag, p in args if not isinstance(p, str)]
    packed = fn.packed()
    st_params += [camel(p.c) for p in packed]
    sel = keywords(fn.name, st_params)
    desc = "#(call 'vm:core' '%s' (%s) i64)" % (fn.export, " ".join(TAG_ST[t] for t, _ in args))
    L = [sel, "\t\"%s\"" % fn.proto.replace('"', "'"), "\t<ffiSite>"]
    temps = ["ffiResult"]
    outs = fn.outs()
    if outs: temps.append("ffiOuts")
    if packed: temps.append("ffiPack")
    L.append("\t| %s |" % " ".join(temps))
    if outs: L.append("\tffiOuts := ByteArray new: %d." % (8 * len(outs)))
    if packed: L.append("\tffiPack := self pack: {%s}." % ". ".join(camel(p.c) for p in packed))
    vals = []
    for tag, p in args:
        if p == "pack": vals.append("(self slice: ffiPack)")
        elif p == "outs": vals.append("(self slice: ffiOuts)")
        elif p.sliced: vals.append("(self slice: %s)" % camel(p.c))
        else: vals.append(camel(p.c))
    n = len(vals)
    if n == 0: inv = "tryInvoke0"
    else: inv = "tryInvoke%d: %s" % (n, " with: ".join(vals))
    L.append("\tffiResult := (self ffiSite: %s)\n\t\t%s." % (desc, inv))
    ok = "#(%s)" % " ".join(str(c) for c in fn.ok)
    if fn.is_status: L.append("\tself check: ffiResult in: %s allowing: %s." % (st_string(fn.name), ok))
    else: L.append("\tself check: ffiResult in: %s." % st_string(fn.name))
    for i, p in enumerate(packed):
        if p.role == "outarray": L.append("\tself unpack: ffiPack at: %d into: %s." % (i + 1, camel(p.c)))
    if outs:
        kinds = []
        for p in outs:
            kinds.append("#float" if p.role == "out" and p.t.kind in ("float", "double") else ("#uint" if p.role == "devalloc" or (p.role == "out" and not p.t.signed and p.t.kind != "enum") else "#int"))
        if len(outs) == 1: L.append("\t^self outs: ffiOuts at: 1 kind: %s" % kinds[0])
        else: L.append("\t^{%s}" % ". ".join("self outs: ffiOuts at: %d kind: %s" % (i + 1, k) for i, k in enumerate(kinds)))
    else:
        L.append("\t^ffiResult")
    L.append("!")
    return "\n".join(L)

def gen_smalltalk(lib, hdr, fns, constants):
    L = ["CudaLibraryAPI subclass: #%s\n\tinstanceVariableNames: ''\n\tclassVariableNames: ''\n\tpackage: 'System-CUDA'!\n" % lib.cls]
    L.append("%s comment: %s!\n" % (lib.cls, st_string(
        "I am %s (%s, from %s) as the VM's cuda_* exports give it: one class-side method a C function, its arguments checked in the VM before the call (handles, device pointers inside a live allocation, host ByteArrays long enough), a failure signalled as a CudaError with the library's own name and description of the status. Out-parameters are my answers. %s docs/cuda.md."
        % (lib.name, " ".join(lib.sonames[:1]), lib.header, GENERATED))))
    L.append("!%s class methodsFor: 'library'!" % lib.cls)
    L.append("libraryName\n\t^%s\n!" % st_string(lib.name))
    L.append("ffiAvailable\n\t<ffiSite>\n\t^(self ffiSite: #(call 'vm:core' 'cuda_%s_available' () i64)) tryInvoke0\n!" % lib.name)
    L.append("ffiStatusText: code kind: kind into: slice\n\t<ffiSite>\n\t^(self ffiSite: #(call 'vm:core' 'cuda_%s_status_text' (i64 i64 writableBytesWithLength) i64)) tryInvoke3: code with: kind with: slice\n!" % lib.name)
    L.append("constants\n\t\"The library's constants, name and value.\"\n\t^#(%s)\n! !\n" % " ".join("%s %d" % (st_string(k), v) for k, v in constants))
    L.append("!%s class methodsFor: 'generated'!" % lib.cls)
    for fn in fns:
        L.append(st_method(fn))
    L[-1] += " !"
    return "\n".join(L) + "\n"

def gen(libs):
    global ALL_HANDLES
    for lib in libs:
        for h in lib.handles:
            if h in lib.aliases: continue
            if h not in ALL_HANDLES: ALL_HANDLES.append(h)
            if h in lib.nullable: NULLABLE.add(h)
    handle_ids = {h: i + 1 for i, h in enumerate(ALL_HANDLES)}
    # handle T alias U: T is the same handle type as U (CUstream and cudaStream_t), its ids good for both
    for lib in libs:
        for h, target in lib.aliases.items():
            if target not in handle_ids: die("%s: handle %s aliases %s, which no library declares before" % (lib.name, h, target))
            handle_ids[h] = handle_ids[target]
            if h in lib.nullable: NULLABLE.add(h)
    c_lines, h_lines, uefi, exports = [], [], [], []
    names_table = []
    exports.append((800, "cuda_session", [], []))
    exports.append((801, "cuda_live", [], [("kind", "int64_t", 3)]))
    c_lib_bodies = []
    st_files = {}
    for li, lib in enumerate(libs):
        try:
            hdr = Header(lib)
        except subprocess.CalledProcessError as e:
            die("%s: cannot preprocess %s: %s" % (lib.name, lib.header, e.stderr[:400]))
        names_table.append(lib.sonames)
        exports.append((lib.key, "cuda_%s_available" % lib.name, [], []))
        exports.append((lib.key + 1, "cuda_%s_status_text" % lib.name, [], [("status", "int64_t", 3), ("kind", "int64_t", 3), ("out", "uint8_t *", 9), ("outLength", "uint64_t", None)]))
        c_lib_bodies.append(gen_text(lib, hdr, li))
        fns = []
        for i, spec in enumerate(lib.fns):
            if spec["retired"]: continue
            fn = Fn(lib, hdr, spec, lib.key + 2 + i, handle_ids)
            fns.append(fn)
            sl = slots(fn)
            if len(sl) > 16: die("%s takes %d C slots, more than 16: pack its arrays" % (fn.name, len(sl)))
            exports.append((fn.key, fn.export, fn, sl))
            c_lines.append("/* %s */\n%s {\n%s\n}\n" % (fn.proto, c_proto_of(fn.export, c_slots(fn)), fn.c_body(li)))
        constants = []
        for pat in lib.constants:
            if pat.endswith("*"):
                pool = list(hdr.consts) + [m for m in hdr.macros if re.match(r"^-?\d+$", hdr.macros[m])]
                for k in sorted(set(c for c in pool if c.startswith(pat[:-1]))):
                    constants.append((k, hdr.constant(k)))
            else:
                constants.append((pat, hdr.constant(pat)))
        st_files[lib.cls] = gen_smalltalk(lib, hdr, fns, constants)
    keys = [e[0] for e in exports]
    if len(set(keys)) != len(keys): die("export keys overlap: give a library a higher key")
    # header
    H = ["/* Samaltak's CUDA library exports (cuda_*, FFIPrimitives-cuda): checked wrappers of NVIDIA's libraries, loaded",
         "   with dlopen on first use (cudalib.h). %s */" % GENERATED,
         "#ifndef SAMALTAK_NATIVE_CUDALIB_GEN_H", "#define SAMALTAK_NATIVE_CUDALIB_GEN_H", "#include <stdint.h>", "",
         "#define SAMALTAK_CUDA_LIBS %d" % len(libs), "#define SAMALTAK_CUDA_HANDLE_TYPES %d" % len(ALL_HANDLES), ""]
    protos = []
    for key, export, fn, sl in exports:
        protos.append(c_proto_of(export, c_slots(fn) if isinstance(fn, Fn) else sl))
    H += [p + ";" for p in protos] + ["", "#endif", ""]
    # C
    C = ["/* %s */" % GENERATED, "#include \"cudalib_gen.h\"", "#include \"cudalib.h\"", "", "#if defined(SAMALTAK_UEFI)", ""]
    for p in protos:
        args = re.search(r"\((.*)\)", p).group(1)
        voids = " ".join("(void)%s;" % a.split()[-1].lstrip("*") for a in args.split(", ") if a != "void")
        C.append("%s { %s return SAMALTAK_CUDA_REJECT_UNAVAILABLE; }" % (p, voids))
    C += ["", "#else", "", "#include <stdlib.h>", "", "const char *const *const cudalib_sonames[SAMALTAK_CUDA_LIBS] = {"]
    for s in names_table:
        C.append("    (const char *const[]){ %s, NULL }," % ", ".join('"%s"' % x for x in s))
    C += ["};", "const char *const cudalib_names[SAMALTAK_CUDA_LIBS] = { %s };" % ", ".join('"%s"' % l.name for l in libs), ""]
    C.append("const char *const cudalib_handle_names[SAMALTAK_CUDA_HANDLE_TYPES + 1] = { NULL, %s };" % ", ".join('"%s"' % h for h in ALL_HANDLES))
    C.append("")
    C += c_lib_bodies + c_lines + ["#endif", ""]
    ext, back = gen_lowtalk(libs, [(k, e, f, sl if not isinstance(f, Fn) else c_slots_lowtalk(f)) for k, e, f, sl in exports])
    out = {"vm/native/cudalib_gen.h": "\n".join(H), "vm/native/cudalib_gen.c": "\n".join(C),
           "src/VM-Jit/FFIPrimitives-cuda.extension.st": ext, "src/VM-Jit/CudaBackend.st": back}
    for cls, text in st_files.items():
        out["src/System-CUDA/%s.st" % cls] = text
    return out

