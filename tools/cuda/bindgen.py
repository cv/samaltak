#!/usr/bin/env python3
"""Generate Samaltak's CUDA library bindings from NVIDIA's headers (docs/cuda.md).

Reads tools/cuda/bindings.spec (the libraries and functions to bind), preprocesses each library's header with the C
compiler, and writes
  vm/native/cudalib_gen.h, vm/native/cudalib_gen.c   C wrappers: dlopen the library, check every argument, call
  src/VM-Jit/CudaBackend.st                          the wrappers as a CLibrary for the VM's Lowtalk
  src/VM-Jit/FFIPrimitives-cuda.extension.st         the wrappers as approved FFI exports (vm:core cuda_*)
  src/System-CUDA/<Class>.st                         the image's binding class per library (CudaLibraryAPI)
Run from the repository root where the headers are installed (the CUDA toolkit; cuOpt's wheel for cuOpt: CUOPT_PREFIX);
the build needs no toolkit, since the output is committed. Then "make translate" (vm/gen).

  tools/cuda/bindgen.py [--check]     --check: fail if the generated files differ from the committed ones
"""
import os, re, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CUDA_INCLUDE = os.environ.get("CUDA_INCLUDE", "/usr/local/cuda/include")
os.environ.setdefault("CUOPT_PREFIX", os.path.expanduser("~/.local/share/samaltak-cuopt/venv/lib/python3.12/site-packages"))
GENERATED = "Generated by tools/cuda/bindgen.py from tools/cuda/bindings.spec; do not edit."

# Wrapper results below zero: the call did not reach the library (cudalib.h).
REJECT = {"unavailable": -1, "symbol": -2, "handle": -3, "device": -4, "slice": -5, "full": -6, "argument": -7}

INT_TYPES = {
    "char": (8, True), "signed char": (8, True), "unsigned char": (8, False), "short": (16, True),
    "unsigned short": (16, False), "int": (32, True), "signed": (32, True), "unsigned": (32, False),
    "unsigned int": (32, False), "long": (64, True), "unsigned long": (64, False), "long long": (64, True),
    "unsigned long long": (64, False), "int8_t": (8, True), "uint8_t": (8, False), "int16_t": (16, True),
    "uint16_t": (16, False), "int32_t": (32, True), "uint32_t": (32, False), "int64_t": (64, True),
    "uint64_t": (64, False), "size_t": (64, False), "ssize_t": (64, True), "uintptr_t": (64, False),
    "intptr_t": (64, True), "long int": (64, True), "long unsigned int": (64, False), "short int": (16, True),
    "long long int": (64, True), "long long unsigned int": (64, False), "unsigned long int": (64, False),
}

def die(msg):
    sys.exit("bindgen: " + msg)

# ---------------------------------------------------------------- spec

class Lib:
    def __init__(self, name, cls, key, header, includes):
        self.name, self.cls, self.key, self.header, self.includes = name, cls, key, header, includes
        self.sonames, self.status, self.text, self.handles, self.nullable = [], None, None, [], set()
        self.pointers, self.constants, self.fns, self.aliases = "out", [], [], {}

def parse_spec(path):
    libs = []
    for n, raw in enumerate(open(path), 1):
        line = raw.split("#", 1)[0].strip() if not raw.lstrip().startswith("#") else ""
        if not line:
            continue
        w = line.split()
        if w[0] == "lib":
            opts = dict(zip(w[3::2], w[4::2]))
            inc = w[w.index("include") + 1:] if "include" in w else []
            libs.append(Lib(w[1], w[2], int(opts["key"]), opts["header"], [os.path.expanduser(os.path.expandvars(i)) for i in inc]))
            continue
        lib = libs[-1]
        if w[0] == "soname": lib.sonames = w[1:]
        elif w[0] == "status": lib.status = w[1]
        elif w[0] == "text": lib.text = w[1:]
        elif w[0] == "handle":
            lib.handles.append(w[1])
            if "null" in w[2:]: lib.nullable.add(w[1])
            if "alias" in w[2:]: lib.aliases[w[1]] = w[w.index("alias") + 1]
        elif w[0] == "pointers": lib.pointers = w[1]
        elif w[0] == "constants": lib.constants += w[1:]
        elif w[0] in ("fn", "retired"):
            f = {"c": w[1], "name": w[1], "ok": [], "pack": False, "roles": {}, "require": [], "retired": w[0] == "retired", "line": n}
            i = 2
            while i < len(w):
                if w[i] == "as": f["name"] = w[i + 1]; i += 2; continue
                if w[i] == "pack": f["pack"] = True; i += 1; continue
                if w[i] == "ok":
                    i += 1
                    while i < len(w) and "=" not in w[i] and w[i] not in ("as", "pack"):
                        f["ok"].append(w[i]); i += 1
                    continue
                p, role = w[i].split("=", 1)
                if p == "require": f["require"].append(role)
                else: f["roles"][p] = role
                i += 1
            lib.fns.append(f)
        else:
            die("%s:%d: unknown directive %s" % (path, n, w[0]))
    return libs

# ---------------------------------------------------------------- headers

def strip_attributes(s):
    out, i = [], 0
    while True:
        j = s.find("__attribute__", i)
        if j < 0:
            out.append(s[i:]); break
        out.append(s[i:j])
        k = s.index("(", j); depth = 0
        while True:
            if s[k] == "(": depth += 1
            elif s[k] == ")":
                depth -= 1
                if depth == 0: break
            k += 1
        i = k + 1
    s = "".join(out)
    for word in ("__extension__", "__restrict", "__inline", "__asm__"):
        s = s.replace(word, " ")
    return s

class Header:
    def __init__(self, lib):
        incs = [CUDA_INCLUDE] + lib.includes
        with tempfile.NamedTemporaryFile("w", suffix=".c", delete=False) as t:
            t.write("#include <%s>\n" % lib.header)
        args = ["cc", "-E", "-P"] + ["-I" + i for i in incs] + [t.name]
        text = subprocess.run(args, check=True, capture_output=True, text=True).stdout
        defs = subprocess.run(["cc", "-E", "-dM"] + ["-I" + i for i in incs] + [t.name], check=True, capture_output=True, text=True).stdout
        os.unlink(t.name)
        self.macros = {}
        for m in re.finditer(r"^#define (\w+) (.+)$", defs, re.M):
            self.macros[m.group(1)] = m.group(2).strip()
        text = strip_attributes(re.sub(r"^\s*#.*$", "", text, flags=re.M))
        self.typedefs, self.enums, self.consts, self.protos = {}, {}, {}, {}
        for stmt in self.statements(text):
            self.statement(stmt)

    def statements(self, text):
        depth, start = 0, 0
        for i, c in enumerate(text):
            if c == "{": depth += 1
            elif c == "}": depth -= 1
            elif c == ";" and depth == 0:
                yield " ".join(text[start:i].split())
                start = i + 1

    def statement(self, s):
        s = re.sub(r'^extern\s+(?:"C"\s*)?', "", s)
        for m in re.finditer(r"enum\s*(\w*)\s*\{([^}]*)\}", s):
            self.enum(m.group(1), m.group(2))
        if s.startswith("typedef"):
            body = s[len("typedef"):].strip()
            fp = re.search(r"\(\s*\*\s*(\w+)\s*\)\s*\(", body)
            if fp:
                self.typedefs[fp.group(1)] = "void *"; return
            body = re.sub(r"\{[^{}]*\}", " ", re.sub(r"\{[^{}]*\{[^{}]*\}[^{}]*\}", " ", body))
            m = re.match(r"(.*?)(\w+)\s*(\[[^\]]*\])?$", body)
            if m:
                self.typedefs[m.group(2)] = m.group(1).strip() + (" *" if m.group(3) else "")
            return
        m = re.match(r"(.*?)\b(\w+)\s*\((.*)\)$", s)
        if m and "{" not in s and "(" not in m.group(1):
            self.protos[m.group(2)] = (m.group(1).strip(), m.group(3).strip())

    def enum(self, name, body):
        value, names = -1, []
        for item in body.split(","):
            item = item.strip()
            if not item: continue
            if "=" in item:
                k, v = [x.strip() for x in item.split("=", 1)]
                value = self.eval(v)
            else:
                k = item; value += 1
            self.consts[k] = value
            names.append(k)
        if name: self.enums[name] = names

    def eval(self, expr):
        e = re.sub(r"\b(\w+)\b", lambda m: str(self.consts[m.group(1)]) if m.group(1) in self.consts else m.group(1), expr)
        e = re.sub(r"(?<=\d)[uUlL]+\b", "", e)
        return int(eval(e, {}, {}))

    def constant(self, name):
        if name in self.consts: return self.consts[name]
        if name in self.macros:
            try: return self.eval(self.macros[name])
            except Exception: pass
        die("no integer constant " + name)

    def resolve(self, name):
        """A function name through a macro such as #define cublasSgemm cublasSgemm_v2."""
        seen = 0
        while name in self.macros and re.match(r"^\w+$", self.macros[name]) and seen < 8:
            name = self.macros[name]; seen += 1
        return name

# ---------------------------------------------------------------- types

class CType:
    """kind: int, float, double, void, ptr (opaque), enum; ptr: depth of * in the parameter; name: the typedef name."""
    def __init__(self, text, hdr):
        self.text = " ".join(text.replace("*", " * ").split())
        words = [w for w in self.text.split() if w not in ("const", "volatile", "struct", "union", "restrict")]
        self.depth = words.count("*")
        self.const = self.text.startswith("const ")
        base = " ".join(w for w in words if w != "*")
        self.name = base
        self.kind, self.bits, self.signed = self.base(base, hdr, 0)

    def base(self, base, hdr, n):
        if n > 20: die("typedef loop at " + base)
        if base == "enum" or base.startswith("enum "): return ("enum", 32, True)
        if base in INT_TYPES: return ("int",) + INT_TYPES[base]
        if base == "float": return ("float", 32, True)
        if base == "double": return ("double", 64, True)
        if base == "void": return ("void", 0, False)
        if base in hdr.typedefs:
            t = hdr.typedefs[base]
            if "*" in t: return ("ptr", 64, False)
            words = [w for w in t.replace("*", " ").split() if w not in ("const", "volatile")]
            if words and words[0] in ("struct", "union"): return ("struct", 0, False)
            return self.base(" ".join(words), hdr, n + 1)
        if base in hdr.enums: return ("enum", 32, True)
        die("unknown type " + base)

def split_params(text):
    if text in ("", "void"): return []
    parts, depth, cur = [], 0, ""
    for c in text:
        if c == "(": depth += 1
        if c == ")": depth -= 1
        if c == "," and depth == 0:
            parts.append(cur.strip()); cur = ""
        else:
            cur += c
    parts.append(cur.strip())
    out = []
    for p in parts:
        p = re.sub(r"\[\s*\]$", " *", p)
        m = re.match(r"(.*?)(\w+)$", p)
        out.append((m.group(1).strip(), m.group(2)))
    return out

def scalar_tag(kind, bits, signed):
    if kind == "float": return "f32"
    if kind == "double": return "f64"
    if kind == "enum": return "i32"
    if bits <= 32: return "i32" if signed or bits < 32 else "u32"
    return "i64" if signed else "u64"

TAG_C = {"i32": "int32_t", "u32": "uint32_t", "i64": "int64_t", "u64": "uint64_t", "f32": "float", "f64": "double"}
TAG_NUM = {"i32": 1, "u32": 2, "i64": 3, "u64": 4, "f64": 6, "bytes": 8, "wbytes": 9, "f32": 16}
TAG_ST = {"i32": "i32", "u32": "u32", "i64": "i64", "u64": "u64", "f32": "f32", "f64": "f64", "bytes": "bytesWithLength", "wbytes": "writableBytesWithLength"}

def abi_c(kind, bits, signed, depth):
    if depth: return "void *"
    if kind == "float": return "float"
    if kind == "double": return "double"
    if kind == "void": return "void"
    if kind == "ptr": return "void *"
    if kind == "enum": return "int32_t"
    return ("int%d_t" if signed else "uint%d_t") % bits

def elem_c(t):
    """The C element type a T * points to, for sizes and P()."""
    if t.depth > 1 or t.kind == "ptr": return "void *"
    if t.kind == "void": return "uint8_t"
    return abi_c(t.kind, t.bits, t.signed, 0)

def camel(name):
    parts = [p for p in name.split("_") if p]
    s = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    s = s[:1].lower() + s[1:]
    return s if s not in ("self", "super", "true", "false", "nil", "thisContext") else s + "Arg"

# ---------------------------------------------------------------- functions

class Param:
    pass

class Fn:
    def __init__(self, lib, hdr, spec, key, handle_ids):
        self.lib, self.spec, self.key, self.name = lib, spec, key, spec["name"]
        self.handle_ids = handle_ids
        self.symbol = hdr.resolve(spec["c"])
        if self.symbol not in hdr.protos: die("%s: no prototype for %s" % (lib.name, self.symbol))
        ret, params = hdr.protos[self.symbol]
        self.proto = "%s %s(%s)" % (ret, self.symbol, params)
        self.ret = CType(ret, hdr)
        self.is_status = self.ret.depth == 0 and self.ret.name == lib.status
        self.export = "cuda_" + self.name
        self.ok = [hdr.constant(c) for c in spec["ok"]]
        self.pack = spec["pack"]
        self.params = []
        roles = dict(spec["roles"])
        for ctext, cname in split_params(params):
            p = Param()
            p.c, p.t = cname, CType(ctext, hdr)
            role = roles.pop(cname, None)
            p.role, _, p.expr = (role or self.default_role(p)).partition(":")
            p.handle = None
            base = p.t.name
            if base in handle_ids: p.handle = base
            self.params.append(p)
        if roles: die("%s: no parameters %s" % (self.name, ", ".join(roles)))
        for p in self.params: self.check_role(p, hdr, handle_ids)

    def default_role(self, p):
        t = p.t
        if t.depth == 0:
            if p.t.name in self.lib.handles or p.t.name in ALL_HANDLES: return "handle"
            if t.kind in ("int", "enum", "float", "double"): return "scalar"
            die("%s: cannot pass %s %s" % (self.name, t.text, p.c))
        if t.depth == 1 and (t.name in self.lib.handles or t.name in ALL_HANDLES): return "handleout"
        if t.depth == 1 and t.kind == "int" and t.bits == 8 and t.const: return "cstr"
        if t.depth == 1 and t.kind in ("int", "enum", "float", "double"):
            if t.const and self.lib.pointers == "out": die("%s: annotate %s" % (self.name, p.c))
            return "out" if self.lib.pointers == "out" and not t.const else "dev"
        die("%s: annotate %s (%s)" % (self.name, p.c, t.text))

    def check_role(self, p, hdr, handle_ids):
        r, t = p.role, p.t
        ok = {
            "scalar": t.depth == 0, "value": t.depth == 1 and t.kind in ("int", "enum", "float", "double"),
            "handle": t.depth == 0 and p.handle is not None, "handleout": t.depth == 1 and p.handle is not None,
            "free": p.handle is not None and t.depth <= 1, "out": t.depth == 1 and t.kind in ("int", "enum", "float", "double"),
            "dev": t.depth == 1 or (t.depth == 0 and t.name == "CUdeviceptr"), "devfree": t.depth == 1,
            "null": t.depth >= 1, "params": t.depth == 2, "devalloc": t.depth == 2, "in": t.depth == 1,
            "outarray": t.depth == 1 and not t.const, "cstr": t.depth == 1 and t.kind == "int" and t.bits == 8,
            "const": t.depth == 0,
        }
        if r not in ok: die("%s: unknown role %s" % (self.name, r))
        if not ok[r]: die("%s: role %s does not fit %s %s" % (self.name, r, t.text, p.c))
        if r == "free" and p.expr and p.expr not in handle_ids: die("%s: no handle type %s" % (self.name, p.expr))
        if r == "params" and self.pack: die("%s: params cannot be packed" % self.name)
        if r == "const":
            p.value = hdr.constant(p.expr) if re.match(r"^[A-Za-z_]\w*$", p.expr) else int(p.expr, 0)
        p.sliced = r in ("in", "outarray", "cstr", "params")
        p.packed = p.sliced and self.pack
        if p.handle: p.handle_id = handle_ids[p.handle]

    # The FFI arguments: (tag, C name, Smalltalk name), slices once.
    def ffi_args(self):
        args = []
        for p in self.params:
            r = p.role
            if r == "scalar": args.append((scalar_tag(p.t.kind, p.t.bits, p.t.signed), p))
            elif r == "value": args.append((scalar_tag(p.t.kind, p.t.bits, p.t.signed), p))
            elif r in ("handle", "free"): args.append(("i64", p))
            elif r in ("dev", "devfree"): args.append(("u64", p))
            elif p.sliced and not p.packed: args.append(("wbytes" if r == "outarray" else "bytes", p))
        if self.pack:
            args.append(("wbytes" if any(p.role == "outarray" for p in self.params) else "bytes", "pack"))
        if self.outs():
            args.append(("wbytes", "outs"))
        return args

    def outs(self):
        return [p for p in self.params if p.role in ("out", "handleout", "devalloc")]

    def packed(self):
        return [p for p in self.params if p.packed]

    def c_args(self):
        out = []
        for tag, p in self.ffi_args():
            n = p if isinstance(p, str) else "a_" + p.c
            if tag in ("bytes", "wbytes"):
                out.append(("const uint8_t *" if tag == "bytes" else "uint8_t *", n))
                out.append(("uint64_t", n + "_len"))
            else:
                out.append((TAG_C[tag], n))
        return out

    def c_prototype(self):
        args = ", ".join("%s%s%s" % (t, "" if t.endswith("*") else " ", n) for t, n in self.c_args()) or "void"
        return "int64_t samaltak_%s(%s)" % (self.export, args)

    def expr(self, e):
        names = {p.c for p in self.params}
        e = re.sub(r"\bTAG\((\w+)\)", r"t_\1", e)
        e = re.sub(r"\bP\((\w+)\)", r"p_\1", e)
        e = re.sub(r"\bMAT\(", "SAMALTAK_CUDA_MAT(", e)
        return re.sub(r"(?<![\w.])(\w+)\b", lambda m: "a_" + m.group(1) if m.group(1) in names else m.group(1), e)

    def c_body(self, lib_index):
        L = []
        w = L.append
        w("    static void *fn;")
        w("    if (!fn && !(fn = cudalib_symbol(%d, \"%s\"))) return cudalib_missing(%d);" % (lib_index, self.symbol, lib_index))
        outs = self.outs()
        if outs:
            w("    if (outs_len < %d) return SAMALTAK_CUDA_REJECT_SLICE;" % (8 * len(outs)))
        packed = self.packed()
        if packed:
            w("    if (!cudalib_pack_ok(pack, pack_len, %d)) return SAMALTAK_CUDA_REJECT_SLICE;" % len(packed))
        for e in self.spec["require"]:
            if "P(" not in e and "TAG(" not in e:
                w("    if (!(%s)) return SAMALTAK_CUDA_REJECT_ARGUMENT;" % self.expr(e))
        call, post, setup, cleanup = [], [], [], []
        k = 0
        pi = 0
        for p in self.params:
            r, n, a = p.role, p.c, "a_" + p.c
            ec = elem_c(p.t)
            if r == "scalar":
                call.append("(%s)%s" % (abi_c(p.t.kind, p.t.bits, p.t.signed, 0), a))
            elif r == "const":
                call.append("(%s)%d" % (abi_c(p.t.kind, p.t.bits, p.t.signed, 0), p.value))
            elif r == "null":
                call.append("NULL")
            elif r == "value":
                w("    %s v_%s = (%s)%s;" % (ec, n, ec, a)); call.append("&v_" + n)
            elif r in ("handle", "free"):
                w("    void *h_%s; int64_t t_%s;" % (n, n))
                w("    if (!cudalib_handle_get(%d, %s, %d, &h_%s, &t_%s)) return SAMALTAK_CUDA_REJECT_HANDLE;"
                  % (p.handle_id, a, 1 if p.handle in NULLABLE else 0, n, n))
                call.append("&h_" + n if p.t.depth == 1 else "h_" + n)
                if r == "free" and p.expr: post.append(("always", "    cudalib_handle_drop_tagged(%d, %s);" % (self.handle_ids[p.expr], a)))
                if r == "free": post.append(("always", "    cudalib_handle_drop(%s);" % a))
            elif r == "handleout":
                w("    void *o_%s = NULL;" % n); call.append("&o_" + n)
                tag = self.expr(p.expr) if p.expr else "0"
                post.append(("success", "    if (o_%s) { int64_t id = cudalib_handle_new(%d, o_%s, (int64_t)(%s)); if (id < 0) return id; cudalib_put_i64(outs, %d, id); }" % (n, p.handle_id, n, tag, k)))
                k += 1
            elif r == "out":
                w("    %s o_%s = 0;" % (ec, n)); call.append("&o_" + n)
                put = "cudalib_put_f64" if p.t.kind in ("float", "double") else ("cudalib_put_i64" if p.t.signed or p.t.kind == "enum" else "cudalib_put_u64")
                post.append(("always", "    %s(outs, %d, o_%s);" % (put, k, n)))
                k += 1
            elif r == "devalloc":
                w("    int64_t n_%s = (int64_t)(%s);" % (n, self.expr(p.expr)))
                w("    if (n_%s < 0) return SAMALTAK_CUDA_REJECT_ARGUMENT;" % n)
                w("    if (!cudalib_device_room()) return SAMALTAK_CUDA_REJECT_FULL;")
                w("    void *o_%s = NULL;" % n); call.append("&o_" + n)
                post.append(("success", "    cudalib_device_add((uint64_t)(uintptr_t)o_%s, (uint64_t)n_%s); cudalib_put_u64(outs, %d, (uint64_t)(uintptr_t)o_%s);" % (n, n, k, n)))
                k += 1
            elif r == "devfree":
                w("    if (%s && !cudalib_device_is_base(%s)) return SAMALTAK_CUDA_REJECT_DEVICE;" % (a, a))
                call.append("(void *)(uintptr_t)" + a)
                post.append(("always", "    cudalib_device_drop(%s);" % a))
            elif r == "dev":
                ext = "(int64_t)(%s)" % self.expr(p.expr) if p.expr else "0"
                w("    int64_t n_%s = %s;" % (n, ext))
                w("    if (n_%s < 0 || !cudalib_device_ok(%s, (uint64_t)n_%s * sizeof(%s))) return SAMALTAK_CUDA_REJECT_DEVICE;" % (n, a, n, ec))
                call.append("(void *)(uintptr_t)" + a if p.t.depth else "(uint64_t)" + a)
            elif r == "params":
                # cuLaunchKernel's extra: the parameter area as one buffer (CU_LAUNCH_PARAM_BUFFER_POINTER 1,
                # CU_LAUNCH_PARAM_BUFFER_SIZE 2, CU_LAUNCH_PARAM_END 0); none when it is empty
                w("    const uint8_t *s_%s = %s; uint64_t l_%s = %s_len;" % (n, a, n, a))
                w("    size_t z_%s = (size_t)l_%s;" % (n, n))
                w("    void *x_%s[] = { (void *)1, (void *)s_%s, (void *)2, &z_%s, (void *)0 };" % (n, n, n))
                call.append("l_%s ? x_%s : NULL" % (n, n))
            elif p.sliced:
                if p.packed:
                    w("    %suint8_t *s_%s; uint64_t l_%s;" % ("" if r == "outarray" else "const ", n, n))
                    w("    cudalib_pack_get(pack, %d, (const uint8_t **)&s_%s, &l_%s);" % (pi, n, n)); pi += 1
                else:
                    w("    %suint8_t *s_%s = %s; uint64_t l_%s = %s_len;" % ("" if r == "outarray" else "const ", n, a, n, a))
                if r == "cstr":
                    setup.append("    char *c_%s = cudalib_cstring(s_%s, l_%s);" % (n, n, n))
                    setup.append("    if (!c_%s) { %s return SAMALTAK_CUDA_REJECT_FULL; }" % (n, " ".join(cleanup)))
                    cleanup.append("free(c_%s);" % n)
                    call.append("c_" + n)
                else:
                    w("    int64_t n_%s = (int64_t)(%s);" % (n, self.expr(p.expr)))
                    w("    if (n_%s < 0 || (uint64_t)n_%s > l_%s / sizeof(%s)) return SAMALTAK_CUDA_REJECT_SLICE;" % (n, n, n, ec))
                    w("    %s%s *p_%s = (%s%s *)s_%s; (void)p_%s;" % ("" if r == "outarray" else "const ", ec, n, "" if r == "outarray" else "const ", ec, n, n))
                    call.append("(void *)p_" + n)
        for e in self.spec["require"]:
            if "P(" in e or "TAG(" in e:
                w("    if (!(%s)) return SAMALTAK_CUDA_REJECT_ARGUMENT;" % self.expr(e))
        L += setup
        fp = "%s (*)(%s)" % (abi_c(self.ret.kind, self.ret.bits, self.ret.signed, self.ret.depth),
                             ", ".join(abi_c(p.t.kind, p.t.bits, p.t.signed, p.t.depth) for p in self.params) or "void")
        invoke = "((%s)fn)(%s)" % (fp, ", ".join(call))
        if self.ret.kind == "void" and self.ret.depth == 0:
            w("    %s;" % invoke); w("    int64_t r = 0;")
        else:
            w("    int64_t r = (int64_t)%s;" % invoke)
        if cleanup: w("    " + " ".join(cleanup))
        success = "r == 0" if self.is_status else "1"
        for when, s in post:
            w(s if when == "always" else "    if (%s) {\n    %s\n    }" % (success, s))
        w("    return r;")
        return "\n".join(L)

