def gen_text(lib, hdr, li):
    """samaltak_cuda_<lib>_available and _status_text."""
    L = ["int64_t samaltak_cuda_%s_available(void) { return cudalib_load(%d) ? 1 : SAMALTAK_CUDA_REJECT_UNAVAILABLE; }" % (lib.name, li), ""]
    L.append("int64_t samaltak_cuda_%s_status_text(int64_t status, int64_t kind, uint8_t *out, uint64_t outLength) {" % lib.name)
    t = lib.text or []
    if t and t[0] in ("enum", "macros"):
        names = hdr.enums[t[1]] if t[0] == "enum" else t[1:]
        L.append("    (void)kind;")
        L.append("    const char *s = NULL;")
        L.append("    switch (status) {")
        seen = set()
        for n in names:
            v = hdr.constant(n)
            if v in seen: continue
            seen.add(v)
            L.append("    case %d: s = \"%s\"; break;" % (v, n))
        L.append("    }")
    else:
        L.append("    if (!cudalib_load(%d)) return SAMALTAK_CUDA_REJECT_UNAVAILABLE;" % li)
        L.append("    const char *s = NULL;")
        for kind, fname in enumerate(t):
            ret, params = hdr.protos[hdr.resolve(fname)]
            two = len(split_params(params)) == 2
            L.append("    if (kind == %d) {" % kind)
            L.append("        void *f = cudalib_symbol(%d, \"%s\");" % (li, hdr.resolve(fname)))
            if two:
                L.append("        if (f) ((int (*)(int32_t, const char **))f)((int32_t)status, &s);")
            else:
                L.append("        if (f) s = ((const char *(*)(int32_t))f)((int32_t)status);")
            L.append("    }")
    L.append("    return cudalib_text(s, out, outLength);")
    L.append("}")
    L.append("")
    return "\n".join(L)

def main():
    libs = parse_spec(os.path.join(ROOT, "tools/cuda/bindings.spec"))
    out = gen(libs)
    check = "--check" in sys.argv
    stale = []
    for path, text in out.items():
        full = os.path.join(ROOT, path)
        old = open(full).read() if os.path.exists(full) else None
        if old != text:
            stale.append(path)
            if not check:
                os.makedirs(os.path.dirname(full), exist_ok=True)
                open(full, "w").write(text)
    if check and stale: die("out of date: " + ", ".join(stale))
    print("\n".join(("changed " if stale.count(p) else "same    ") + p for p in out))

if __name__ == "__main__":
    main()
