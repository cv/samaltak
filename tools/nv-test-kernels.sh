#!/bin/sh
# Compiles tests/nv/test-kernels.cu for sm_121 (the GB10) with nvcc and writes src/Tests-NV/NvTestKernels.st, which holds
# the cubin in Base64, so building the image never needs nvcc. Rerun after changing the kernels.
# usage: tools/nv-test-kernels.sh   (NVCC=/path/to/nvcc to override; default /usr/local/cuda/bin/nvcc)
set -eu
cd "$(dirname "$0")/.."
NVCC=${NVCC:-/usr/local/cuda/bin/nvcc}
ARCH=sm_121
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
"$NVCC" -cubin -arch=$ARCH -O3 -o "$tmp/k.cubin" tests/nv/test-kernels.cu
version=$("$NVCC" --version | sed -n 's/.*release \([0-9.]*\).*/\1/p')
sha=$(sha256sum "$tmp/k.cubin" | cut -d' ' -f1)
size=$(wc -c <"$tmp/k.cubin" | tr -d ' ')
out=src/Tests-NV/NvTestKernels.st
{
  printf "Object subclass: #NvTestKernels\n\tinstanceVariableNames: ''\n\tclassVariableNames: ''\n\tpackage: 'Tests-NV'!\n\n"
  printf "NvTestKernels comment: 'I am generated by tools/nv-test-kernels.sh from tests/nv/test-kernels.cu (nvcc %s -cubin -arch=%s -O3: %s bytes, SHA-256 %s); do not edit me, regenerate me. cubin answers the cubin, an NvCubin with the kernels vadd, fill, dims, copy16, reverse256, local1k and lookup that NvCubinTest reads and NvGpuTest runs.'!\n\n" "$version" "$ARCH" "$size" "$sha"
  printf "!NvTestKernels class methodsFor: 'kernels'!\ncubin\n\t^NvCubin on: (Base64 decode: self cubinBase64)\n!\nsha256\n\t^'%s'\n!\ncubinBase64\n\t\"The cubin in Base64, in lines.\"\n\t^'" "$sha"
  base64 -w 120 "$tmp/k.cubin"
  printf "'\n! !\n"
} >"$out"
echo "wrote $out ($size bytes of cubin)"
